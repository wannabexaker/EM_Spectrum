import type { FrequencyFeature, ScientificConfidence, SpectrumCategory, SpectrumMode, UniversalVibrationCategory } from '@/types/spectrum'

const DAY = 86400
const YEAR = 365.2425 * DAY

interface AtlasInput {
  id: string
  label: string
  shortLabel: string
  frequency: number
  bandwidth?: number
  visualCategory?: SpectrumCategory | 'technology'
  atlasCategory: UniversalVibrationCategory
  confidence: ScientificConfidence
  aliases: string[]
  family: string
  detail: string
  color: string
  minZoom: number
  modeVisibility?: SpectrumMode | 'both'
  listPath: string[]
  periodSeconds?: number
  sources?: FrequencyFeature['sources']
}

const byPeriod = (seconds: number) => 1 / seconds
const byBpm = (bpm: number) => bpm / 60
const span = (min: number, max: number) => Math.max(max - min, Math.max(min, 1e-14) * 0.08)
const center = (min: number, max: number) => Math.sqrt(min * max)

function item(input: AtlasInput): FrequencyFeature {
  return {
    id: `atlas-${input.id}`,
    label: input.label,
    shortLabel: input.shortLabel,
    frequency_center: input.frequency,
    frequency_bandwidth: input.bandwidth ?? Math.max(input.frequency * 0.08, 1e-14),
    category: input.visualCategory ?? 'sound',
    family: input.family,
    detail: input.detail,
    color: input.color,
    minZoom: input.minZoom,
    aliases: input.aliases,
    atlasCategory: input.atlasCategory,
    confidence: input.confidence,
    periodSeconds: input.periodSeconds ?? (input.frequency > 0 ? 1 / input.frequency : undefined),
    modeVisibility: input.modeVisibility ?? 'both',
    listPath: ['Universal Vibrations Atlas', ...input.listPath],
    sources: input.sources,
  }
}

